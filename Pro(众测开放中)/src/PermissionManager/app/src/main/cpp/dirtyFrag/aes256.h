static const uint8_t _rcon[11] = {0x00,0x01,0x02,0x04,0x08,0x10,0x20,0x40,0x80,0x1b,0x36};

static inline uint8_t _xtime(uint8_t a) {
    return (uint8_t)((a << 1) ^ (a >> 7 ? 0x1b : 0));
}
static inline uint8_t _gmul(uint8_t a, uint8_t b) {
    uint8_t r = 0;
    for (int i = 0; i < 8; i++) {
        if (b & 1) r ^= a;
        a = _xtime(a); b >>= 1;
    }
    return r;
}

static void _aes256_expand(const uint8_t k[32], uint32_t rk[60]) {
    for (int i = 0; i < 8; i++)
        rk[i] = ((uint32_t)k[4*i]<<24)|((uint32_t)k[4*i+1]<<16)|((uint32_t)k[4*i+2]<<8)|k[4*i+3];
    for (int i = 8; i < 60; i++) {
        uint32_t t = rk[i-1];
        if (i % 8 == 0) {
            /* RotWord then SubWord then Rcon */
            t = ((uint32_t)_sbox[(t>>16)&0xff]<<24)|((uint32_t)_sbox[(t>>8)&0xff]<<16)|
                ((uint32_t)_sbox[t&0xff]<<8)|(uint32_t)_sbox[(t>>24)&0xff];
            t ^= (uint32_t)_rcon[i/8] << 24;
        } else if (i % 8 == 4) {
            t = ((uint32_t)_sbox[(t>>24)&0xff]<<24)|((uint32_t)_sbox[(t>>16)&0xff]<<16)|
                ((uint32_t)_sbox[(t>>8)&0xff]<<8)|(uint32_t)_sbox[t&0xff];
        }
        rk[i] = rk[i-8] ^ t;
    }
}

static inline void _add_rk(uint8_t s[16], const uint32_t *rk) {
    for (int c = 0; c < 4; c++) {
        s[4*c+0] ^= (rk[c]>>24)&0xff;
        s[4*c+1] ^= (rk[c]>>16)&0xff;
        s[4*c+2] ^= (rk[c]>>8)&0xff;
        s[4*c+3] ^=  rk[c]&0xff;
    }
}

static inline void _inv_shift_rows(uint8_t s[16]) {
    uint8_t t;
    /* Row 1: right-shift by 1 */
    t = s[13]; s[13]=s[9]; s[9]=s[5]; s[5]=s[1]; s[1]=t;
    /* Row 2: right-shift by 2 (swap pairs) */
    t = s[2]; s[2]=s[10]; s[10]=t;
    t = s[6]; s[6]=s[14]; s[14]=t;
    /* Row 3: right-shift by 3 */
    t = s[3]; s[3]=s[7]; s[7]=s[11]; s[11]=s[15]; s[15]=t;
}

static inline void _inv_sub_bytes(uint8_t s[16]) {
    for (int i = 0; i < 16; i++) s[i] = _isbox[s[i]];
}

static inline void _inv_mix_cols(uint8_t s[16]) {
    for (int c = 0; c < 4; c++) {
        uint8_t s0=s[4*c], s1=s[4*c+1], s2=s[4*c+2], s3=s[4*c+3];
        s[4*c+0] = _gmul(0x0e,s0)^_gmul(0x0b,s1)^_gmul(0x0d,s2)^_gmul(0x09,s3);
        s[4*c+1] = _gmul(0x09,s0)^_gmul(0x0e,s1)^_gmul(0x0b,s2)^_gmul(0x0d,s3);
        s[4*c+2] = _gmul(0x0d,s0)^_gmul(0x09,s1)^_gmul(0x0e,s2)^_gmul(0x0b,s3);
        s[4*c+3] = _gmul(0x0b,s0)^_gmul(0x0d,s1)^_gmul(0x09,s2)^_gmul(0x0e,s3);
    }
}

/* AES-256 ECB single-block decrypt: ct[16] → pt[16] */
static void aes256_ecb_decrypt(const uint8_t key[32], const uint8_t ct[16], uint8_t pt[16]) {
    uint32_t rk[60];
    _aes256_expand(key, rk);
    uint8_t s[16];
    for (int i = 0; i < 16; i++) s[i] = ct[i];

    _add_rk(s, &rk[56]);   /* AddRoundKey round 14 */

    for (int r = 13; r >= 1; r--) {
        _inv_shift_rows(s);
        _inv_sub_bytes(s);
        _add_rk(s, &rk[4*r]);
        _inv_mix_cols(s);
    }

    _inv_shift_rows(s);
    _inv_sub_bytes(s);
    _add_rk(s, &rk[0]);    /* AddRoundKey round 0 */

    for (int i = 0; i < 16; i++) pt[i] = s[i];
}

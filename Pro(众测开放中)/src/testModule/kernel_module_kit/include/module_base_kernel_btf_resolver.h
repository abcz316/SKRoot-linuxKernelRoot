#pragma once
#include <stdio.h>
#include <stdint.h>
#include <stdlib.h>
#include <string.h>

namespace kernel_module {

/***************************************************************************
 * 内核 BTF 元数据解析器（动态偏移量）
 * 通过内核提供的 BTF 信息，动态获取结构体成员偏移量和结构体大小。
 *
 * 注意：不是所有内核都支持该功能。内核版本必须>=5.10.0，且需编译时开启：CONFIG_DEBUG_INFO_BTF=y
 *      如果内核没有开启 BTF，或者运行时无法获取 vmlinux BTF 信息，下面的接口将无法正常解析。
 ***************************************************************************/

/***************************************************************************
 * 通过BTF解析内核结构体中的成员偏移量
 * 参数：
 *   struct_name  结构体名称，例如 "task_struct"、"cred"
 *   member_name  成员名称，例如 "__state"、"uid"
 *   offset       输出参数，返回该成员相对结构体起始的字节偏移量
 * 返回：OK 表示成功；其他值为错误码
 ***************************************************************************/
KModErr btf_resolve_member_offset(const char *struct_name, const char *member_name, uint32_t &offset);

/***************************************************************************
 * 通过BTF解析内核结构体的大小
 * 参数：
 *   struct_name  结构体名称，例如 "task_struct"
 *   size         输出参数，返回结构体大小（单位：字节）
 * 返回：OK 表示成功；其他值为错误码
 ***************************************************************************/
KModErr btf_resolve_struct_size(const char *struct_name, uint32_t &size);

}
